-- Depois de 3 dias, o pedido entra no sino do CRM para que a equipe abra o
-- WhatsApp já com link e código gerados pelo endpoint community-admin.
create or replace function public.crm_generate_review_invite_reminders()
returns integer
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_inserted integer;
begin
  insert into public.crm_notifications (
    recipient_user_id, recipient_reseller_id, kind, severity,
    title, message, event_key, metadata
  )
  select
    profile.user_id,
    null,
    'review_invite_due',
    'info',
    'Pedido pronto para pedir avaliação',
    'O pedido ' || coalesce(order_row.external_order_number, left(order_row.id::text, 8)) ||
      ' já pode receber o convite de avaliação pelo WhatsApp.',
    'review-invite-due:' || order_row.id::text,
    jsonb_build_object(
      'order_id', order_row.id,
      'customer_id', order_row.customer_id,
      'action', 'create_review_invite'
    )
  from public.orders as order_row
  cross join public.profiles as profile
  where profile.role = 'admin'
    and profile.active = true
    and order_row.payment_status = 'pago'
    and order_row.order_date <= now() - interval '3 days'
    and order_row.status not in ('cancelado', 'reembolsado')
    and exists (
      select 1
      from public.order_items as item
      where item.order_id = order_row.id
        and item.product_id is not null
        and not exists (
          select 1 from public.product_reviews as review
          where review.order_item_id = item.id
        )
    )
    and not exists (
      select 1
      from public.review_invites as invite
      where invite.order_id = order_row.id
        and invite.status in ('pending', 'used')
    )
  on conflict (recipient_user_id, event_key) do nothing;

  get diagnostics v_inserted = row_count;
  return v_inserted;
end;
$$;

revoke all on function public.crm_generate_review_invite_reminders() from public, anon, authenticated;
