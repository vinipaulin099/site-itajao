-- Insere um e-mail uma única vez. A função fica inacessível ao navegador e é
-- usada apenas pelas Edge Functions e pelos gatilhos internos.
create or replace function public.enqueue_email(
  p_category text,
  p_template_key text,
  p_recipient_email text,
  p_recipient_name text,
  p_sender_kind text,
  p_subject text,
  p_payload jsonb,
  p_idempotency_key text,
  p_related_order_id uuid default null,
  p_related_customer_id uuid default null,
  p_resource_type text default null,
  p_resource_id uuid default null,
  p_priority smallint default 100
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_email text := lower(trim(coalesce(p_recipient_email, '')));
  v_status text := 'pending';
  v_id uuid;
  v_reason text;
begin
  if v_email = '' or v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'E-mail inválido';
  end if;

  select reason into v_reason
    from public.email_suppressions
   where email = v_email;

  if v_reason in ('bounced', 'complained', 'manual')
     or (v_reason = 'unsubscribed' and p_category = 'marketing') then
    v_status := 'suppressed';
  end if;

  insert into public.email_outbox (
    category, template_key, recipient_email, recipient_name, sender_kind,
    subject, payload, status, priority, next_attempt_at, idempotency_key,
    related_order_id, related_customer_id, resource_type, resource_id
  ) values (
    p_category, p_template_key, v_email, nullif(trim(p_recipient_name), ''),
    p_sender_kind, p_subject, coalesce(p_payload, '{}'::jsonb), v_status,
    p_priority, case when v_status = 'pending' then now() else null end,
    p_idempotency_key, p_related_order_id, p_related_customer_id,
    p_resource_type, p_resource_id
  )
  on conflict (idempotency_key) do nothing
  returning id into v_id;

  if v_id is null then
    select id into v_id
      from public.email_outbox
     where idempotency_key = p_idempotency_key;
  end if;

  return v_id;
end;
$$;

-- Reserva lotes com SKIP LOCKED para evitar disparos duplicados quando duas
-- execuções do agendador se sobrepõem.
create or replace function public.claim_email_outbox(p_limit integer default 25)
returns setof public.email_outbox
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  update public.email_outbox
     set status = 'pending',
         claim_token = null,
         claimed_at = null,
         next_attempt_at = now(),
         provider_error = coalesce(provider_error, 'Processamento anterior expirou.')
   where status = 'processing'
     and claimed_at < now() - interval '15 minutes';

  return query
  with picked as (
    select id
      from public.email_outbox
     where status in ('pending', 'failed')
       and attempts < max_attempts
       and coalesce(next_attempt_at, now()) <= now()
     order by priority asc, created_at asc
     for update skip locked
     limit greatest(1, least(coalesce(p_limit, 25), 100))
  )
  update public.email_outbox as outbox
     set status = 'processing',
         attempts = outbox.attempts + 1,
         claimed_at = now(),
         claim_token = gen_random_uuid(),
         updated_at = now()
    from picked
   where outbox.id = picked.id
  returning outbox.*;
end;
$$;

create or replace function public.complete_email_outbox(
  p_id uuid,
  p_claim_token uuid,
  p_success boolean,
  p_provider_message_id text default null,
  p_error text default null
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_updated integer;
begin
  update public.email_outbox
     set status = case
           when p_success then 'sent'
           when attempts >= max_attempts then 'dead'
           else 'failed'
         end,
         provider_message_id = case when p_success then p_provider_message_id else provider_message_id end,
         provider_error = case when p_success then null else left(coalesce(p_error, 'Falha desconhecida.'), 1500) end,
         sent_at = case when p_success then now() else sent_at end,
         next_attempt_at = case
           when p_success or attempts >= max_attempts then null
           else now() + make_interval(mins => (power(2, least(attempts, 6)))::integer)
         end,
         claimed_at = null,
         claim_token = null,
         updated_at = now()
   where id = p_id
     and status = 'processing'
     and claim_token = p_claim_token;

  get diagnostics v_updated = row_count;
  return v_updated = 1;
end;
$$;

