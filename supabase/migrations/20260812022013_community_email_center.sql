-- E-mails de mudanças do pedido são gerados no banco para cobrir tanto o
-- checkout quanto atualizações feitas depois no CRM/Bling.
create or replace function public.queue_store_order_email()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_customer_name text;
  v_customer_email text;
  v_public_token uuid;
  v_template text;
  v_subject text;
  v_key text;
begin
  select public_token
    into v_public_token
    from public.site_order_integrations
   where order_id = new.id;

  if v_public_token is null then
    return new;
  end if;

  select full_name, lower(email)
    into v_customer_name, v_customer_email
    from public.customers
   where id = new.customer_id;

  if coalesce(v_customer_email, '') = '' then
    return new;
  end if;

  if old.payment_status is distinct from new.payment_status then
    if new.payment_status = 'pago' then
      v_template := 'payment_approved';
      v_subject := 'Pagamento aprovado — pedido ' || coalesce(new.external_order_number, left(new.id::text, 8));
    elsif new.payment_status = 'cancelado' then
      v_template := 'payment_cancelled';
      v_subject := 'Pagamento cancelado — pedido ' || coalesce(new.external_order_number, left(new.id::text, 8));
    elsif new.payment_status = 'reembolsado' then
      v_template := 'payment_refunded';
      v_subject := 'Pagamento reembolsado — pedido ' || coalesce(new.external_order_number, left(new.id::text, 8));
    end if;

    if v_template is not null then
      v_key := 'order:' || new.id::text || ':payment:' || new.payment_status;
      perform public.enqueue_email(
        'transactional', v_template, v_customer_email, v_customer_name,
        'customer', v_subject,
        jsonb_build_object(
          'customer_name', v_customer_name,
          'order_id', new.id,
          'order_number', new.external_order_number,
          'total_amount', new.total_amount,
          'public_token', v_public_token,
          'payment_status', new.payment_status
        ),
        v_key, new.id, new.customer_id, 'order', new.id, 20
      );
    end if;
  end if;

  if new.status = 'enviado'
     and (old.status is distinct from new.status or old.tracking_code is distinct from new.tracking_code) then
    perform public.enqueue_email(
      'transactional', 'order_shipped', v_customer_email, v_customer_name,
      'customer', 'Seu Café Itajaó foi enviado',
      jsonb_build_object(
        'customer_name', v_customer_name,
        'order_id', new.id,
        'order_number', new.external_order_number,
        'public_token', v_public_token,
        'tracking_code', new.tracking_code,
        'expected_delivery_date', new.expected_delivery_date
      ),
      'order:' || new.id::text || ':shipped:' || coalesce(new.tracking_code, 'sem-rastreio'),
      new.id, new.customer_id, 'order', new.id, 30
    );
  end if;

  if new.status = 'entregue' and old.status is distinct from new.status then
    perform public.enqueue_email(
      'transactional', 'order_delivered', v_customer_email, v_customer_name,
      'customer', 'Pedido entregue — aproveite seu Café Itajaó',
      jsonb_build_object(
        'customer_name', v_customer_name,
        'order_id', new.id,
        'order_number', new.external_order_number,
        'public_token', v_public_token,
        'delivered_at', coalesce(new.delivered_at, now())
      ),
      'order:' || new.id::text || ':delivered',
      new.id, new.customer_id, 'order', new.id, 30
    );
  end if;

  return new;
end;
$$;

